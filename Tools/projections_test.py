"""Exercise the real projection CLI against tiny private record/target files."""
import argparse
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest

PROJECTIONS = Path(__file__).with_name('projections.py').resolve()
ENTRY = '''import importlib.util, pathlib, sys
script, root = map(pathlib.Path, sys.argv[1:3])
spec = importlib.util.spec_from_file_location('fixture_projections', script)
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)
module.ROOT = str(root)
module.STORE = str(root / 'db')
raise SystemExit(module.main(sys.argv[3:]))
'''
SENTINELS = {
    'MEASUREMENTS.md': b'keep the existing measurements\n',
    'PLAN.md': b'keep the existing plan\n',
}
EXPECTED = {
    'MEASUREMENTS.md': (
        '<!-- Generated by Tools/projections.py from db/records/measurements/ '
        'Edit the records, then run the script; this file is a projection. -->\n\n'
        '## Measured fixture\nMeasured body.\n'),
    'PLAN.md': (
        '<!-- Generated by Tools/projections.py from db/records/design/, db/records/plan/ '
        'Edit the records, then run the script; this file is a projection. -->\n\n'
        '## Design fixture\nDesign body.\n\n'
        '## Planned fixture\nPlan body.\n'),
}
ALIASES = [('measurements', 'MEASUREMENTS.md'), ('MEASUREMENTS.md', 'MEASUREMENTS.md'),
           ('plan', 'PLAN.md'), ('PLAN.md', 'PLAN.md')]


class ProjectionSelectors(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='slotstream-projection-selector-')
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name).resolve()
        for folder, doc, order, title, body in [
                ('measurements', 'measurements', 10, 'Measured fixture', 'Measured body.'),
                ('design', 'plan', 10, 'Design fixture', 'Design body.'),
                ('plan', 'plan', 20, 'Planned fixture', 'Plan body.')]:
            target = self.root / 'db' / 'records' / folder / 'fixture.md'
            target.parent.mkdir(parents=True)
            target.write_text(
                '---\ntitle: ' + title + '\ndoc: ' + doc + '\norder: ' + str(order) +
                '\nlevel: 2\n---\n' + body + '\n', encoding='utf-8')
        self.reset_targets()

    def reset_targets(self):
        for name, content in SENTINELS.items():
            (self.root / name).write_bytes(content)

    def targets(self):
        return {name: (self.root / name).read_bytes() for name in SENTINELS}

    def write_current(self, name):
        (self.root / name).write_text(EXPECTED[name], encoding='utf-8')

    def run_cli(self, *arguments):
        # The real DOCS, parser and renderer remain unchanged. Only repository
        # paths point at this test's tiny records and target sentinels.
        return subprocess.run(
            [sys.executable, '-I', '-B', '-c', ENTRY, str(PROJECTIONS),
             str(self.root), *arguments],
            cwd=self.root, env={'PATH': os.defpath, 'HOME': str(self.root)},
            stdin=subprocess.DEVNULL, text=True, capture_output=True, timeout=5)

    def expect_usage_error(self, *arguments):
        before = self.targets()
        result = self.run_cli(*arguments)
        # Assert preservation first so the original misspelled-option behavior
        # leaves direct before/after mutation evidence in the RED traceback.
        self.assertEqual(self.targets(), before, result.stdout + result.stderr)
        self.assertEqual(result.returncode, 2, result.stdout + result.stderr)
        self.assertIn('usage:', result.stderr)
        self.assertNotIn('missing folder', result.stderr)
        self.assertNotIn('wrote ', result.stdout)

    def test_default_generates_both(self):
        result = self.run_cli()
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertEqual(result.stderr, '')
        self.assertEqual(self.targets(), {k: v.encode() for k, v in EXPECTED.items()})
        self.assertEqual(result.stdout.count('wrote '), 2)

    def test_each_alias_generates_only_selected_document(self):
        for alias, selected in ALIASES:
            with self.subTest(alias=alias):
                self.reset_targets()
                result = self.run_cli(alias)
                self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
                self.assertEqual(result.stderr, '')
                expected = dict(SENTINELS)
                expected[selected] = EXPECTED[selected].encode()
                self.assertEqual(self.targets(), expected)
                self.assertEqual(result.stdout.count('wrote '), 1)

    def test_default_check_accepts_current_documents(self):
        for name in EXPECTED:
            self.write_current(name)
        before = self.targets()
        result = self.run_cli('--check')
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertEqual(result.stderr, '')
        self.assertEqual(result.stdout.count(' is current'), 2)
        self.assertEqual(self.targets(), before)

    def test_default_check_rejects_stale_documents_without_writing(self):
        before = self.targets()
        result = self.run_cli('--check')
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertEqual(self.targets(), before)
        for name in EXPECTED:
            self.assertIn(name + ' differs from its records', result.stderr)

    def test_each_alias_check_ignores_unselected_stale_document(self):
        for alias, selected in ALIASES:
            with self.subTest(alias=alias):
                self.reset_targets()
                self.write_current(selected)
                before = self.targets()
                result = self.run_cli('--check', alias)
                self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
                self.assertEqual(result.stderr, '')
                self.assertEqual(result.stdout, selected + ' is current\n')
                self.assertEqual(self.targets(), before)

    def test_each_alias_check_rejects_selected_stale_document(self):
        for alias, selected in ALIASES:
            with self.subTest(alias=alias):
                self.reset_targets()
                for name in EXPECTED:
                    if name != selected:
                        self.write_current(name)
                before = self.targets()
                result = self.run_cli('--check', alias)
                self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
                self.assertIn(selected + ' differs from its records', result.stderr)
                self.assertEqual(result.stdout, '')
                self.assertEqual(self.targets(), before)

    def test_check_flag_can_appear_between_selectors(self):
        for name in EXPECTED:
            self.write_current(name)
        before = self.targets()
        for arguments in [('plan', '--check', 'measurements'),
                          ('PLAN.md', '--check', 'MEASUREMENTS.md')]:
            with self.subTest(arguments=arguments):
                result = self.run_cli(*arguments)
                self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
                self.assertEqual(result.stderr, '')
                self.assertEqual(result.stdout.count(' is current'), 2)
                self.assertEqual(self.targets(), before)

    def test_repeated_selectors_do_not_repeat_generation(self):
        result = self.run_cli('plan', 'PLAN.md', 'plan')
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertEqual(result.stderr, '')
        self.assertEqual(result.stdout.count('wrote '), 1)
        expected = dict(SENTINELS)
        expected['PLAN.md'] = EXPECTED['PLAN.md'].encode()
        self.assertEqual(self.targets(), expected)

    def test_invalid_check_selector_is_a_usage_error(self):
        self.expect_usage_error('--check', 'PLAN.MD')

    def test_invalid_generation_selector_is_a_usage_error(self):
        self.expect_usage_error('PLAN.MD')

    def test_unknown_flag_refuses_generation(self):
        self.expect_usage_error('--chek')

    def test_abbreviated_check_flag_refuses_generation(self):
        self.expect_usage_error('--chec')

    def test_mixed_valid_invalid_selectors_refuse_all_writes(self):
        self.expect_usage_error('measurements', 'PLAN.MD')

    def test_unknown_flag_with_valid_selector_refuses_all_writes(self):
        self.expect_usage_error('--chek', 'plan')

    def test_invalid_arguments_are_rejected_before_record_access(self):
        shutil.rmtree(self.root / 'db')
        self.expect_usage_error('measurements', 'PLAN.MD')

    def test_help_does_not_generate_documents(self):
        before = self.targets()
        result = self.run_cli('--help')
        self.assertEqual(self.targets(), before, result.stdout + result.stderr)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertEqual(result.stderr, '')
        self.assertIn('usage:', result.stdout)

    def test_help_is_available_without_reading_records(self):
        shutil.rmtree(self.root / 'db')
        before = self.targets()
        result = self.run_cli('--help')
        self.assertEqual(self.targets(), before, result.stdout + result.stderr)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertEqual(result.stderr, '')
        self.assertIn('usage:', result.stdout)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(add_help=False)
    parser.add_argument('--script', type=Path, default=PROJECTIONS)
    options, remaining = parser.parse_known_args()
    PROJECTIONS = options.script.resolve()
    unittest.main(argv=[sys.argv[0], *remaining])
